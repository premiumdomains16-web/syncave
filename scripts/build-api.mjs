// Bundles the API (server/edge.ts + shared code + npm packages) into one ES module
// that Supabase Edge Functions run as-is: supabase/functions/api/index.js.
//   npm run build:api
import { build } from "esbuild";
import { fileURLToPath } from "url";
import path from "path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

await build({
  entryPoints: [path.join(root, "server/edge.ts")],
  outfile: path.join(root, "supabase/functions/api/index.js"),
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  // Prefer each package's browser/worker build: no Node-only code in the bundle.
  mainFields: ["browser", "module", "main"],
  conditions: ["worker", "browser", "import", "default"],
  // Only reached in Node (tests); Deno takes the Deno.resolveDns path first.
  external: ["node:*"],
  minify: false,
  legalComments: "none",
  banner: { js: "// Generated by scripts/build-api.mjs from server/. Do not edit; edit server/ and rebuild." },
  logLevel: "info",
});
